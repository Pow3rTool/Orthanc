# OBO token re-validation at the control plane (run_control).
# XConnect forwards the OBO bearer it validated; Orthanc INDEPENDENTLY verifies it
# (tenant JWKS + audience + issuer + expiry + scope) and derives the principal
# from the verified token — so a compromised XConnect can't fabricate an identity.
# OBO_AUDIENCE is the XConnect *API* app's audience (app-id GUID or api:// URI),
# NOT the Orthanc SSO app above. Enforcement auto-enables once OBO_AUDIENCE is set;
# run_control refuses to start if enforcement is on but tenant/audience are missing.
# ---------------------------------------------------------------------------
OBO_AUDIENCE = env('ORTHANC_OBO_AUDIENCE', default='')
OBO_TENANT_ID = env('ORTHANC_OBO_TENANT_ID', default=AZURE_TENANT_ID)
