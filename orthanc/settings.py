OBO_VALIDATE_TOKEN = env.bool('ORTHANC_OBO_VALIDATE_TOKEN', default=bool(OBO_AUDIENCE))

# Fail CLOSED in production: with DEBUG off, independent OBO re-validation is
# mandatory. Without it the control plane trusts XConnect's asserted principal AND
# azp verbatim — a compromised broker could fabricate any identity and walk through
# the agent jail. Mirrors the SECRET_KEY guard above; the assertion-trust path is
# strictly a local-dev convenience (ORTHANC_DEBUG=true).
if not DEBUG and not OBO_VALIDATE_TOKEN:
    from django.core.exceptions import ImproperlyConfigured
    raise ImproperlyConfigured(
        'OBO token re-validation is required when DEBUG is off: set '
        'ORTHANC_OBO_AUDIENCE (and ORTHANC_OBO_TENANT_ID) so the control plane '
        'independently verifies the forwarded OBO token instead of trusting '
        "XConnect's asserted principal/azp. For LOCAL DEV ONLY, set ORTHANC_DEBUG=true."
    )

